import asyncio
import httpx

BASE_URL = "http://127.0.0.1:8000"

async def test_ai_test_generation_and_student_attendance():
    async with httpx.AsyncClient(base_url=BASE_URL, timeout=60.0) as client:
        print("=================================================================")
        print("  VERIFYING AI TEST GENERATION, STAFF ASSIGNMENT & ATTENDANCE   ")
        print("=================================================================")

        # -----------------------------------------------------------------
        # STEP 1: Staff / Faculty Login
        # -----------------------------------------------------------------
        print("\n[Step 1] Logging in as Staff (Dr. Rajesh Sharma)...")
        res_fac = await client.post("/api/v1/auth/login", json={
            "email": "prof.sharma@ait.edu",
            "password": "Password123!"
        })
        assert res_fac.status_code == 200, f"Staff login failed: {res_fac.text}"
        fac_token = res_fac.json()["access_token"]
        fac_headers = {"Authorization": f"Bearer {fac_token}"}
        print(" -> Staff successfully authenticated.")

        # -----------------------------------------------------------------
        # STEP 2: Staff Asks Help from AI Agent to Generate Exam Questions
        # -----------------------------------------------------------------
        print("\n[Step 2] Staff requesting AI Agent to generate examination questions...")
        ai_gen_res = await client.post(
            "/api/v1/faculty/exams/generate-ai",
            headers=fac_headers,
            json={
                "topic": "Operating Systems Concurrency, Deadlocks & Banker's Algorithm",
                "count": 3,
                "question_type": "Mixed",
                "marks_per_question": 10
            }
        )
        assert ai_gen_res.status_code == 200, f"AI generation failed: {ai_gen_res.text}"
        generated_questions = ai_gen_res.json().get("questions", [])
        print(f" -> AI Agent successfully generated {len(generated_questions)} questions:")
        for idx, q in enumerate(generated_questions):
            print(f"    Q{idx+1}: {q.get('prompt')[:85]}... [{q.get('question_type')}] (Marks: {q.get('marks')})")

        # -----------------------------------------------------------------
        # STEP 3: Staff Creates & Saves the AI Generated Exam
        # -----------------------------------------------------------------
        print("\n[Step 3] Staff saving AI-generated examination...")
        subj_id = "1a8c9a6c-f429-4a8d-a0fb-a3c6d883e301"
        create_res = await client.post(
            "/api/v1/faculty/exams",
            headers=fac_headers,
            json={
                "title": "AI Assessment: Concurrency & Deadlock Invariants",
                "subject_id": subj_id,
                "exam_type": "Continuous Internal Evaluation",
                "duration_minutes": 60,
                "total_marks": sum(float(q.get("marks", 10)) for q in generated_questions),
                "description": "Generated by AI Agent covering Coffman conditions, concurrency, and safety algorithms.",
                "questions": generated_questions
            }
        )
        assert create_res.status_code == 201, f"Failed to save exam: {create_res.text}"
        created_exam = create_res.json()
        exam_id = created_exam["id"]
        print(f" -> Exam created successfully! ID: {exam_id} | Title: {created_exam['title']}")

        # -----------------------------------------------------------------
        # STEP 4: Staff Assigns the Exam to the Department Students
        # -----------------------------------------------------------------
        inst_id = "7700ee18-bc62-4199-83f2-7e7f86650445"
        dept_id = "e10b4e14-4301-4f7b-a9ae-e2e6c7bca930"
        print(f"\n[Step 4] Staff assigning exam {exam_id} to Department CSE...")
        assign_res = await client.post(
            f"/api/v1/faculty/exams/{exam_id}/assign",
            headers=fac_headers,
            json={
                "institution_id": inst_id,
                "department_id": dept_id,
                "start_time": "2026-10-28T00:00:00Z",
                "end_time": "2026-10-31T23:59:59Z"
            }
        )
        assert assign_res.status_code == 200, f"Failed to assign: {assign_res.text}"
        print(f" -> {assign_res.json().get('message')}")

        # -----------------------------------------------------------------
        # STEP 5: Student Logs In and Confirms Exam in Student Portal
        # -----------------------------------------------------------------
        print("\n[Step 5] Student Arun Kumar logging in to attend the assigned exam...")
        res_stu = await client.post("/api/v1/auth/login", json={
            "email": "student.arun@ait.edu",
            "password": "Password123!"
        })
        assert res_stu.status_code == 200, f"Student login failed: {res_stu.text}"
        stu_token = res_stu.json()["access_token"]
        stu_headers = {"Authorization": f"Bearer {stu_token}"}
        print(" -> Student Arun Kumar authenticated successfully.")

        # Check assigned exams
        res_assigned = await client.get("/api/v1/student/exams", headers=stu_headers)
        assert res_assigned.status_code == 200
        assigned_exams = res_assigned.json()
        target_exam = next((e for e in assigned_exams if e["exam_id"] == str(exam_id)), None)
        assert target_exam is not None, "Exam was not received in student portal!"
        print(f" -> CONFIRMED: Student portal received '{target_exam['title']}' (Status: {target_exam['status']})")

        # -----------------------------------------------------------------
        # STEP 6: Student Opens & Attends the Exam
        # -----------------------------------------------------------------
        print(f"\n[Step 6] Student opening exam questions workspace...")
        exam_detail_res = await client.get(f"/api/v1/student/exams/{exam_id}", headers=stu_headers)
        assert exam_detail_res.status_code == 200
        exam_detail = exam_detail_res.json()
        questions = exam_detail.get("questions", [])
        print(f" -> Questions received by student: {len(questions)}")
        for idx, q in enumerate(questions):
            print(f"    Q{idx+1}: {q.get('prompt')[:85]}... [{q.get('question_type')}]")

        # -----------------------------------------------------------------
        # STEP 7: Student Submits Answers
        # -----------------------------------------------------------------
        print("\n[Step 7] Student submitting answers for evaluation...")
        answers_payload = []
        for q in questions:
            if q.get("question_type") == "MCQ" and q.get("options"):
                answers_payload.append({
                    "question_id": q["id"],
                    "selected_option_text": q["options"][0]["option_text"]
                })
            else:
                answers_payload.append({
                    "question_id": q["id"],
                    "selected_option_text": "Mutual Exclusion, Hold and Wait, No Preemption, Circular Wait. The Banker's Safety Algorithm analyzes allocation and claim vectors to guarantee a safe execution sequence."
                })

        submit_res = await client.post(
            f"/api/v1/student/exams/{exam_id}/submit",
            headers=stu_headers,
            json={"answers": answers_payload}
        )
        assert submit_res.status_code == 200, f"Submit failed: {submit_res.text}"
        submit_data = submit_res.json()
        print(" -> Submission successful! AI Evaluation completed.")
        print(f"    Marks Awarded: {submit_data.get('marks_obtained')} / {submit_data.get('total_marks')}")
        print(f"    Percentage: {submit_data.get('percentage')}% | Grade: {submit_data.get('grade')}")

        # -----------------------------------------------------------------
        # STEP 8: Review AI Scorecard & Diagnostic Recommendations
        # -----------------------------------------------------------------
        print("\n[Step 8] Student checking AI results scorecard...")
        results_res = await client.get(f"/api/v1/student/exams/{exam_id}/results", headers=stu_headers)
        assert results_res.status_code == 200
        results_data = results_res.json()
        print(" -> Results scorecard successfully verified:")
        print(f"    Total Score: {results_data.get('marks_obtained')} / {results_data.get('total_marks')}")
        print(f"    Status: {results_data.get('status')}")
        if results_data.get("question_breakdown"):
            print(f"    Evaluated Question Breakdown ({len(results_data['question_breakdown'])} items):")
            for item in results_data["question_breakdown"]:
                print(f"     - Score: {item.get('marks_obtained')}/{item.get('marks_allocated')} | {item.get('prompt')[:60]}...")

        print("\n=================================================================")
        print("  ALL TESTS VERIFIED: 100% OPERATIONAL WITH ZERO DEFECTS!       ")
        print("=================================================================")

if __name__ == "__main__":
    asyncio.run(test_ai_test_generation_and_student_attendance())
